"""Private screenshot storage: an S3-compatible bucket or a local folder."""

from pathlib import Path
from typing import Any, Protocol

import boto3
from botocore.config import Config
from botocore.exceptions import BotoCoreError, ClientError
from starlette.concurrency import run_in_threadpool

from app.core.config import Settings
from app.core.exceptions import AppException

STORAGE_UNAVAILABLE_DETAIL = "Screenshot storage is unavailable"


class ScreenshotStorage(Protocol):
    async def put(self, key: str, data: bytes, content_type: str) -> None: ...

    async def signed_url(self, key: str) -> str | None:
        """A short-lived URL to the object, or None when the API must serve the bytes."""
        ...

    async def read(self, key: str) -> bytes: ...


class S3ScreenshotStorage:
    def __init__(self, settings: Settings) -> None:
        self._bucket = settings.storage_bucket
        self._ttl = settings.screenshot_url_ttl_seconds
        self._client: Any = boto3.client(
            "s3",
            endpoint_url=settings.storage_endpoint,
            region_name=settings.storage_region,
            aws_access_key_id=settings.storage_access_key_id,
            aws_secret_access_key=settings.storage_secret_access_key.get_secret_value(),
            config=Config(signature_version="s3v4", retries={"max_attempts": 3}),
        )

    async def put(self, key: str, data: bytes, content_type: str) -> None:
        try:
            await run_in_threadpool(
                self._client.put_object,
                Bucket=self._bucket,
                Key=key,
                Body=data,
                ContentType=content_type,
            )
        except (BotoCoreError, ClientError) as exc:
            raise AppException(503, STORAGE_UNAVAILABLE_DETAIL) from exc

    async def signed_url(self, key: str) -> str | None:
        url: str = self._client.generate_presigned_url(
            "get_object", Params={"Bucket": self._bucket, "Key": key}, ExpiresIn=self._ttl
        )
        return url

    async def read(self, key: str) -> bytes:
        try:
            response = await run_in_threadpool(
                self._client.get_object, Bucket=self._bucket, Key=key
            )
            body: bytes = await run_in_threadpool(response["Body"].read)
            return body
        except (BotoCoreError, ClientError) as exc:
            raise AppException(503, STORAGE_UNAVAILABLE_DETAIL) from exc


class LocalScreenshotStorage:
    """Development and test storage; keys are generated by the API, never by users."""

    def __init__(self, root: Path) -> None:
        self._root = root.resolve()

    def _path(self, key: str) -> Path:
        path = (self._root / key).resolve()
        if not path.is_relative_to(self._root):
            raise AppException(400, "Invalid storage key")
        return path

    async def put(self, key: str, data: bytes, content_type: str) -> None:
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        await run_in_threadpool(path.write_bytes, data)

    async def signed_url(self, key: str) -> str | None:
        return None

    async def read(self, key: str) -> bytes:
        path = self._path(key)
        if not path.is_file():
            raise AppException(404, "Screenshot not found")
        return await run_in_threadpool(path.read_bytes)


def uses_bucket(settings: Settings) -> bool:
    return all(
        (
            settings.storage_endpoint,
            settings.storage_bucket,
            settings.storage_access_key_id,
            settings.storage_secret_access_key.get_secret_value(),
        )
    )


def build_storage(settings: Settings) -> ScreenshotStorage:
    if uses_bucket(settings):
        return S3ScreenshotStorage(settings)
    return LocalScreenshotStorage(Path(settings.storage_local_path))
